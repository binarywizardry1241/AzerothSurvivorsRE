#!/usr/bin/env python3
"""Generate/check current boss and guardian connections for recovered raid moves.

Reads the selected EXE, checks owning current data, and never compiles or runs a
game. --write updates only the three generated source catalogs.
"""
from script_sources import load_script
import argparse
import json
import re
import struct

from coverage_common import ROOT

def load(name, path):
    module = load_script(name, ROOT/path)
    return module

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--write',action='store_true')
    args=ap.parse_args()
    actions=load('raid_action_inputs','scripts/recover-raid-actions.py')
    target,raw,span,records,_=actions.recover()
    waves=json.loads((ROOT/'docs/analysis/evidence/0.109.0/raid-waves/manifest.json').read_text())
    assert waves['target_sha256']==target['sha256']
    towers=json.loads((ROOT/'docs/analysis/evidence/0.109.0/raid-towers/manifest.json').read_text())
    assert towers['target_sha256']==target['sha256']
    shields=load('raid_shield_inputs','scripts/check-raid-shields.py')
    shield_target,_,_,shield_records=shields.recover()
    assert shield_target['sha256']==target['sha256']
    native=load('raid_native_inputs','scripts/recover-raid-native-catalog.py')
    native_target,_,_,graph=native.recover()
    assert native_target['sha256']==target['sha256']
    special={}
    payloads={}
    for row in records:payloads[(row['native_tag'],tuple(row['payload_words']))]=(10,row['index'])
    for row in waves['records']:payloads[(27,tuple(row['payload_words']))]=(8,row['index'])
    for row in towers['records']:payloads[(12,tuple(row['payload_words']))]=(13,row['index'])
    for row in shield_records:payloads[(23,(row['spell'],row['duration_bits']))]=(14,row['index'])
    for action in graph['actions']:
        for (tag,words),mapped in payloads.items():
            if action['native_tag']==tag and tuple(action['words'][:len(words)])==words:
                special[int(action['record']['va'],16)]=mapped
    ward_index=json.loads((ROOT/'docs/analysis/evidence/0.109.0/raid-wards/index.json').read_text())
    for va,index in ward_index.items():special[int(va,16)]=(15,index)
    def ability(index):
        row=graph['actions'][index];w=row['words'];tag=row['native_tag'];cool=row['repeat_bits']
        v={3:[5,*w[:5],cool],4:[1,w[0],w[1],0,0,0,cool],5:[2,w[0],0,0,0,0,cool],6:[6,*w[:3],0,0,cool],
           7:[9,w[0],0,0,0,0,cool],28:[11,*w[:5],cool],30:[12,*w[:5],cool]}.get(tag)
        if int(row['record']['va'],16) in special:
            semantic,index=special[int(row['record']['va'],16)];v=[semantic,index,0,0,0,0,cool]
        if tag in [18,24]:v=[16,row['index'],0,0,0,0,cool]
        if tag in [0,1,2,32]:v=[18,row['index'],0,0,0,0,cool]
        if v is None:v=[17,row['index'],0,0,0,0,cool]
        return v
    def rust_ability(v):return 'RawBossAbility { words: ['+', '.join(f'0x{x:08x}'for x in v)+'] }'
    native_lines=['//! Complete hash-bound0.109.0 native raid action graph. Generated by',
        '//! scripts/connect-raid-mechanics.py; native payloads are not semantic ABI.',
        'use super::RawBossAbility;',
        '#[derive(Clone, Copy, Debug)]',
        'pub struct NativeAction { pub native_tag: u8, pub words: [u32;12], pub children: &\'static [usize], pub repeat: f32, pub duration: f32, pub ability: RawBossAbility }',
        'pub fn native_action(index: usize) -> RawBossAbility { ACTIONS[index].ability }',
        '#[rustfmt::skip]', 'pub const ACTIONS: &[NativeAction] = &[']
    for row in graph['actions']:
        native_lines.append('    NativeAction { native_tag: %d, words: ['%row['native_tag']+', '.join(f'0x{x:08x}'for x in row['words'])+'], children: &['+', '.join(map(str,row['children']))+f'], repeat: f32::from_bits(0x{row["repeat_bits"]:08x}), duration: f32::from_bits(0x{row["duration_bits"]:08x}), ability: '+rust_ability(ability(row['index']))+' },')
    native_lines.append('];')
    path=ROOT/'crates/azeroth-survivors-re/src/bosses/raid_native_catalog.rs';expected='\n'.join(native_lines)+'\n'
    if args.write:path.write_text(expected)
    else:assert path.read_text()==expected,'Native raid semantic registry drifted'
    counts={};blocks=[];phase_lines=[]
    for boss in graph['bosses']:
        selected=[]
        for m in boss['moves']:
            action=graph['actions'][m['action']];tag=action['native_tag'];counts[tag]=counts.get(tag,0)+1
            selected.append(f'        ScheduledMove {{ native_slot: {m["slot"]}, native_tag: {tag}, ability: '+rust_ability(ability(m['action']))+' },')
        blocks.extend([f'    BossSchedule {{ boss_id: {boss["boss_id"]}, moves: &[',*selected,'    ] },'])
        for phase in boss['phases']:
            action=graph['actions'][phase['action']]
            # Minion phases retain their historical public helper, with one
            # canonical current record owner and the same phase latch.
            if action['native_tag']==5:continue
            phase_lines.append(f'    RaidPhase {{ boss_id: {boss["boss_id"]}, phase_index: {phase["slot"]}, threshold: f32::from_bits(0x{phase["threshold_bits"]:08x}), yell: {json.dumps(phase["yell"])}, native_tag: {action["native_tag"]}, ability: '+rust_ability(ability(phase['action']))+' },')
    path=ROOT/'crates/azeroth-survivors-re/src/bosses/raid_area_catalog.rs';source=path.read_text()
    before,rest=source.split('// BEGIN CURRENT RAID SCHEDULES\n');_,after=rest.split('// END CURRENT RAID SCHEDULES')
    expected=before+'// BEGIN CURRENT RAID SCHEDULES\n'+'\n'.join(blocks)+'\n// END CURRENT RAID SCHEDULES'+after
    before,rest=expected.split('// BEGIN CURRENT RAID PHASES\n');_,after=rest.split('// END CURRENT RAID PHASES')
    expected=before+'// BEGIN CURRENT RAID PHASES\n'+'\n'.join(phase_lines)+'\n// END CURRENT RAID PHASES'+after
    if args.write:path.write_text(expected)
    else:assert source==expected,'Current primary-boss source slots drifted'
    lines=['//! Generated0.109.0 complete guardian signatures, including recursive effects.',
        'use super::signatures::{Signature, Move, Phase};','use crate::bosses::RawBossAbility;','',
        '#[rustfmt::skip]','pub const SIGNATURES: &[Signature] = &[']
    for row in graph['guardians']:
        lines.append(f'    Signature {{ enemy_id: {row["enemy_id"]}, variants: &[')
        for variant in row['variants']:
            lines.append('        &[')
            for move in variant:
                a=graph['actions'][move['action']]
                lines.append(f'            Move {{ native_tag: {a["native_tag"]}, cooldown: f32::from_bits(0x{a["repeat_bits"]:08x}), ability: Some('+rust_ability(ability(move['action']))+') },')
            lines.append('        ],')
        lines.append('    ], phases: &[')
        for phase in row['phases']:
            a=graph['actions'][phase['action']]
            lines.append(f'        Phase {{ native_tag: {a["native_tag"]}, threshold: f32::from_bits(0x{phase["threshold_bits"]:08x}), yell: {json.dumps(phase["yell"],ensure_ascii=False)}, ability: Some('+rust_ability(ability(phase['action']))+') },')
        lines.append('    ] },')
    lines.append('];');expected='\n'.join(lines)+'\n'
    path=ROOT/'crates/azeroth-survivors-re/src/guardians/signature_catalog.rs'
    if args.write:path.write_text(expected)
    else:assert path.read_text()==expected,'Current guardian source connections drifted'
    # The old instant-charge lane must not run beside the new warned charge.
    ai=(ROOT/'crates/azeroth-survivors-re/src/bosses/ai.rs').read_text()
    assert 'selected current schedule is complete' in ai
    print('Current boss source slots:',counts)
    print('Guardian source actions:',sum('ability: Some(' in line for line in lines),'of135 records; no compiler/game')

if __name__=='__main__':main()
