use crate::zones::scholomance;

#[derive(Clone, Copy, Debug)]
pub struct EnemyDefinition {
    pub id: u32,
    pub name: &'static str,
    pub model_id: u32,
    pub scale: f32,
    pub raw_cast: [u32; 4],
    pub raw_2c: u32,
    pub base_hp: f32,
    pub base_damage: f32,
    pub raw_38: f32,
    pub raw_3c: f32,
    pub raw_40: u32,
    pub raw_44: f32,
    pub raw_48: f32,
    pub flag_4c: u8,
}

/// Tag-1 source attack, read by the ordinary actor cast branch.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SpellAttack {
    pub spell_id: u32,
    pub range: f32,
    pub cast_seconds: f32,
}

impl EnemyDefinition {
    /// Other tags remain available in raw_cast; this does not invent an attack for them.
    pub fn spell_attack(&self) -> Option<SpellAttack> {
        (self.raw_cast[0] == 1).then(|| SpellAttack {
            spell_id: self.raw_cast[1],
            range: f32::from_bits(self.raw_cast[2]),
            cast_seconds: f32::from_bits(self.raw_cast[3]),
        })
    }
    /// Record+0x38, copied into the actor's attack interval.
    pub fn attack_interval(&self) -> f32 {
        self.raw_38
    }
    /// Record+0x3c; creation applies the active speed-percent modifier separately.
    pub fn movement_speed(&self) -> f32 {
        self.raw_3c
    }
    /// Record+0x48, compared to elapsed run minutes by the ordinary spawn selector.
    pub fn spawn_minute(&self) -> f32 {
        self.raw_48
    }
    /// Record+0x44, the selector's inverse weight and spawn-budget cost.
    pub fn spawn_cost(&self) -> f32 {
        self.raw_44
    }
}

#[derive(Clone, Copy, Debug)]
pub struct ZoneDefinition {
    pub key: &'static str,
    pub name: &'static str,
    pub center: [f32; 3],
    pub radius: f32,
    pub scalar_e0: f32,
    pub enemies: &'static [EnemyDefinition],
}

impl ZoneDefinition {
    /// Exact catalog lookup; callers choose how to handle an unknown key.
    pub fn by_key(key: &str) -> Option<&'static Self> {
        ZONES.iter().find(|zone| zone.key == key)
    }
    pub fn enemy_by_id(&self, id: u32) -> Option<&'static EnemyDefinition> {
        self.enemies.iter().find(|enemy| enemy.id == id)
    }
}

