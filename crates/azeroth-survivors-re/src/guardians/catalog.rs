//! semantic source records, not declarations of the native in-memory ABI.

use crate::zones::scholomance;

pub use crate::enemies::catalog::EnemyDefinition;

/// Original boss ability record: seven exact 32-bit words, stride 28.
#[derive(Clone, Copy, Debug)]
pub struct RawBossAbility {
    pub words: [u32; 7],
}

#[derive(Clone, Copy, Debug)]
pub struct BossDefinition {
    pub id: u32,
    pub name: &'static str,
    pub yell: &'static str,
    pub model_id: u32,
    pub scale: f32,
    pub raw_3c: u32,
    pub time_minutes: f32,
    pub base_hp: f32,
    pub base_damage: f32,
    pub raw_4c: f32,
    /// Revalidated0.109.0 entrance voice SoundEntries ID; zero omits the voice.
    pub raw_50: u32,
    pub flag_54: u8,
    pub abilities: &'static [RawBossAbility],
}

/// Time/HP pairs copied by native14552b760; final-flag1 rows are skipped.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct HealthKnot {
    pub time_minutes: f32,
    pub base_hp: f32,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct GuardianPoint {
    pub index: usize,
    pub xy: [f32; 2],
}

#[derive(Clone, Copy, Debug)]
pub struct ZoneDefinition {
    pub key: &'static str,
    pub name: &'static str,
    pub center: [f32; 3],
    pub radius: f32,
    pub scalar_e0: f32,
    pub enemies: &'static [EnemyDefinition],
    pub bosses: &'static [BossDefinition],
    pub hp_knots: &'static [HealthKnot],
    pub guardian_radius: Option<f32>,
    pub placement_angle: f32,
    pub guardian_points: &'static [GuardianPoint],
    pub guardian_enemy_indices: &'static [usize],
}

impl ZoneDefinition {
    pub fn by_key(key: &str) -> Option<&'static Self> {
        ZONES.iter().find(|zone| zone.key == key)
    }
}

